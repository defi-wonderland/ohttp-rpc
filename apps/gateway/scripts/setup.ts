#!/usr/bin/env bun
/**
 * Gateway Setup Script
 * 
 * Interactive setup for OHTTP Gateway deployment
 */

import { existsSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Generate a cryptographically secure HPKE seed
 */
function generateHpkeSeed(): string {
  const seedBytes = new Uint8Array(32);
  crypto.getRandomValues(seedBytes);
  
  const base64 = btoa(String.fromCharCode(...seedBytes));
  const base64url = base64
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=/g, '');
    
  return base64url;
}

/**
 * Prompt user for input
 */
async function prompt(question: string, defaultValue?: string): Promise<string> {
  const readline = await import('readline');
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });
  
  return new Promise((resolve) => {
    const fullQuestion = defaultValue 
      ? `${question} (${defaultValue}): `
      : `${question}: `;
      
    rl.question(fullQuestion, (answer) => {
      rl.close();
      resolve(answer.trim() || defaultValue || '');
    });
  });
}

/**
 * Main setup function
 */
async function main() {
  console.log('🚀 OHTTP Gateway Setup');
  console.log('======================');
  console.log('');
  
  const envPath = join(process.cwd(), '.env');
  const envExamplePath = join(process.cwd(), 'env.example');
  
  // Check if .env already exists
  if (existsSync(envPath)) {
    const overwrite = await prompt('.env file already exists. Overwrite? (y/N)', 'n');
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Setup cancelled.');
      return;
    }
  }
  
  console.log('This will help you configure your OHTTP Gateway for deployment.');
  console.log('');
  
  // Load example config as template
  let envContent = '';
  if (existsSync(envExamplePath)) {
    envContent = readFileSync(envExamplePath, 'utf8');
  }
  
  // Gather configuration
  console.log('📡 Server Configuration');
  const port = await prompt('Gateway port', '8788');
  
  console.log('');
  console.log('🔐 Security Configuration');
  const generateNewSeed = await prompt('Generate new HPKE seed? (Y/n)', 'y');
  let hpkeSeed: string;
  
  if (generateNewSeed.toLowerCase() !== 'n') {
    hpkeSeed = generateHpkeSeed();
    console.log('✅ Generated secure HPKE seed');
  } else {
    hpkeSeed = await prompt('Enter HPKE seed (base64url, 32+ chars)');
    if (hpkeSeed.length < 32) {
      console.error('❌ HPKE seed must be at least 32 characters');
      return;
    }
  }
  
  console.log('');
  console.log('🎯 Policy Configuration');
  const allowedTargets = await prompt(
    'Allowed RPC targets (comma-separated)', 
    'https://mainnet.infura.io,https://eth.llamarpc.com'
  );
  
  const maxInnerBytes = await prompt('Max request size (bytes)', '524288');
  
  console.log('');
  console.log('⚙️ Advanced Configuration');
  const requireTls = await prompt('Require TLS for upstream? (Y/n)', 'y');
  const logLevel = await prompt('Log level (debug/info/warn/error)', 'info');
  
  // Build .env content
  const config = [
    '# OHTTP Gateway Configuration',
    '# Generated by setup script',
    '',
    '# Server Configuration',
    `GATEWAY_PORT=${port}`,
    '',
    '# Security Configuration',
    `HPKE_SEED=${hpkeSeed}`,
    'HPKE_SUITE=DHKEM_X25519_HKDF_SHA256+HKDF_SHA256+AES_128_GCM',
    '',
    '# Policy Configuration',
    `ALLOWED_TARGETS=${allowedTargets}`,
    'ALLOWED_HEADERS=content-type,accept,authorization',
    `MAX_INNER_BYTES=${maxInnerBytes}`,
    '',
    '# Upstream Configuration',
    'UPSTREAM_CONNECT_TIMEOUT_MS=3000',
    'UPSTREAM_TOTAL_TIMEOUT_MS=15000',
    '',
    '# Security Settings',
    `REQUIRE_TLS_UPSTREAM=${requireTls.toLowerCase() !== 'n'}`,
    'ALLOW_REDIRECTS=false',
    'DATE_SKEW_TOLERANCE_MS=300000',
    'ENABLE_REPLAY_PROTECTION=true',
    '',
    '# Logging',
    `LOG_LEVEL=${logLevel}`,
    'LOG_INNER_CONTENT=false',
  ].join('\n');
  
  // Write .env file
  writeFileSync(envPath, config);
  
  console.log('');
  console.log('✅ Configuration saved to .env');
  console.log('');
  console.log('🔒 Security Notes:');
  console.log('  - Keep your HPKE seed secret and secure');
  console.log('  - Never commit .env to version control');
  console.log('  - Rotate keys periodically for enhanced security');
  console.log('');
  console.log('🚀 Next Steps:');
  console.log('  - Test configuration: bun run validate-config');
  console.log('  - Start in development: bun run start:dev');
  console.log('  - Start in production: bun run start');
  console.log('');
  console.log('📚 Documentation:');
  console.log('  - See README.md for detailed configuration options');
  console.log('  - Check env.example for all available settings');
}

if (import.meta.main) {
  main().catch(console.error);
}
